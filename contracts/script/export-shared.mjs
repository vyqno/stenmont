// Generates packages/shared/src/abis/*.ts and addresses.ts from forge artifacts and contracts/deployments/*.json.
// Run after `forge build`: node contracts/script/export-shared.mjs   (CI fails if the output drifts)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const contracts = ["PaymentRouter", "PasskeyAccountFactory", "PasskeyAccount"];
const header = "// GENERATED by contracts/script/export-shared.mjs. Do not edit by hand.\n";

mkdirSync(join(root, "packages/shared/src/abis"), { recursive: true });
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, `contracts/out/${name}.sol/${name}.json`), "utf8"));
  const exportName = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(root, `packages/shared/src/abis/${name[0].toLowerCase() + name.slice(1)}.ts`),
    `${header}export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
}
writeFileSync(
  join(root, "packages/shared/src/abis/index.ts"),
  header + contracts.map((n) => `export * from "./${n[0].toLowerCase() + n.slice(1)}";`).join("\n") + "\n",
);

const deployments = JSON.parse(readFileSync(join(root, "contracts/deployments/1874.json"), "utf8"));
writeFileSync(
  join(root, "packages/shared/src/addresses.ts"),
  `${header}export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log("exported:", contracts.join(", "), "and addresses");
