// Isolated v2 ABI artifacts; never rewrites active v1 imports or deployment addresses.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const names = ["PaymentRouterV2", "InvoiceClaimV2", "ReputationRegistryV2", "InvoiceAck", "LedgerAnchor"];
const dir = join(root, "packages/shared/src/abis/v2");
mkdirSync(dir, {recursive:true});
for (const name of names) {
 const {abi} = JSON.parse(readFileSync(join(root,`contracts/out/${name}.sol/${name}.json`),"utf8"));
 const id = name[0].toLowerCase()+name.slice(1);
 writeFileSync(join(dir,`${id}.ts`), `// GENERATED by contracts/script/export-v2.mjs. Not active deployment configuration.\nexport const ${id}Abi = ${JSON.stringify(abi)} as const;\n`);
}
